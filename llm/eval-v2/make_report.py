#!/usr/bin/env python3
"""make_report.py — aggregate eval-v2 results + judgments into a report and a blind review packet.

Outputs:
  <report-dir>/results.md        coding + writing tables (judge scores exclude self-judgments)
  <report-dir>/review_packet.md  blind human review: top-N writers by judge score, labels A-D
  <report-dir>/ballot.txt        fill-in ranking template for the packet
  <key-path>                     label -> model key (kept out of the reports dir; not committed)
"""

import argparse
import collections
import glob
import json
import os
import random
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from judge import CRITERIA  # noqa: E402
from tasks_writing import all_writing_tasks  # noqa: E402

LABELS = "ABCDEFGHIJ"


def load(results_dir, judgments_dir):
    res = {}
    for f in sorted(glob.glob(os.path.join(results_dir, "*.json"))):
        r = json.load(open(f))
        res[r["candidate"]] = r
    judg = []
    for f in sorted(glob.glob(os.path.join(judgments_dir, "*.jsonl"))):
        judg += [json.loads(ln) for ln in open(f) if ln.strip()]
    return res, judg


def judge_table(judg):
    """candidate -> {criterion: mean over non-self judgments}, plus overall + judge list."""
    acc = collections.defaultdict(lambda: collections.defaultdict(list))
    judges = collections.defaultdict(set)
    for j in judg:
        if j.get("self") or not j.get("scores"):
            continue
        for k in CRITERIA:
            acc[j["candidate"]][k].append(j["scores"][k])
        judges[j["candidate"]].add(j["judge"])
    out = {}
    for c, d in acc.items():
        row = {k: round(statistics.mean(v), 2) for k, v in d.items()}
        row["overall"] = round(statistics.mean(row[k] for k in CRITERIA), 2)
        row["n"] = len(d[CRITERIA[0]])
        row["judges"] = sorted(judges[c])
        out[c] = row
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", required=True)
    ap.add_argument("--judgments-dir", required=True)
    ap.add_argument("--report-dir", required=True)
    ap.add_argument("--key-path", required=True)
    ap.add_argument("--shortlist", type=int, default=4)
    a = ap.parse_args()
    res, judg = load(a.results_dir, a.judgments_dir)
    jt = judge_table(judg)
    os.makedirs(a.report_dir, exist_ok=True)
    L = ["# eval-v2 results", "",
         "Generated by `llm/eval-v2/make_report.py`. Method: `llm/eval-v2/README.md`. Raw outputs:",
         "`reports/data/eval-v2/`.", ""]

    # ---- coding ----
    L += ["## Coding (15 tasks, executed against hidden tests)", "",
          "| candidate | greedy pass@1 | sampled pass rate (3x, T=0.6) | bugfix | class | parsing | graph | algorithm | utility | median tok/s |",
          "|:--|:--:|:--:|:--:|:--:|:--:|:--:|:--:|:--:|--:|"]
    cats = ["bugfix", "class", "parsing", "graph", "algorithm", "utility"]
    order = sorted((c for c in res if res[c]["coding"]),
                   key=lambda c: (-res[c]["summary"]["coding_pass_greedy"],
                                  -(res[c]["summary"]["coding_sampled_pass_rate"] or 0)))
    for c in order:
        s, rows = res[c]["summary"], res[c]["coding"]
        per = []
        for cat in cats:
            rs = [r for r in rows if r["category"] == cat]
            per.append(f"{sum(r['pass_greedy'] for r in rs)}/{len(rs)}" if rs else "-")
        L.append(f"| {c} | **{s['coding_pass_greedy']}/{s['coding_tasks']}** | "
                 f"{s['coding_sampled_pass_rate']:.0%} | " + " | ".join(per) + f" | {s['median_tok_s']} |")
    ids = []
    for c in order:
        ids += [r["id"] for r in res[c]["coding"] if r["id"] not in ids]
    L += ["", "Per task (greedy ✓/✗, then sampled passes out of 3):", "",
          "| task | " + " | ".join(order) + " |", "|:--|" + ":--:|" * len(order)]
    for tid in ids:
        cells = []
        for c in order:
            r = next((x for x in res[c]["coding"] if x["id"] == tid), None)
            cells.append("-" if r is None else ("✓" if r["pass_greedy"] else "✗") + f" {r['sampled_passes']}/3")
        L.append(f"| {tid} | " + " | ".join(cells) + " |")

    # ---- writing ----
    L += ["", "## Creative writing (10 prompts x 2 samples, T=0.8)", "",
          "Judge scores are 1-10 means over both local judges, **excluding each judge's scores of "
          "its own outputs**. They are a secondary signal: local judges are about as weak as the "
          "candidates and favour longer text. The blind human ranking (`human_results.md`, once "
          "you've filled in the ballot) is the primary signal.", "",
          "| candidate | judge overall | adherence | craft | originality | voice | coherence | judged samples | length in range | stock phrases /1k words | truncated / empty |",
          "|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
    worder = sorted(res, key=lambda c: -(jt.get(c, {}).get("overall") or 0))
    for c in worder:
        s, j = res[c]["summary"], jt.get(c, {})
        L.append(f"| {c} | **{j.get('overall', '-')}** | " + " | ".join(str(j.get(k, "-")) for k in CRITERIA)
                 + f" | {j.get('n', 0)} | {s['writing_length_ok']}/{s['writing_samples']} | "
                 f"{s['stock_per_1k_words_mean']} | {s['writing_truncated']} / {s['writing_empty']} |")
    jud = sorted({j["judge"] for j in judg})
    L += ["", f"Judges: {', '.join(jud) or 'none'}. Unparseable judge replies: "
          f"{sum(1 for j in judg if j.get('error') == 'unparseable')}.", ""]

    # ---- blind review packet ----
    ranked = [c for c in worder if c in jt] or list(res)
    short = ranked[: a.shortlist]
    tasks = all_writing_tasks()
    key, P, B = {}, ["# Blind writing review", "",
                     f"{len(short)} anonymous writers (the top {len(short)} by judge score), one sample each "
                     "(seed 101). Labels are shuffled per prompt, so 'A' is not the same writer twice. "
                     "Rank each prompt best to worst in `ballot.txt`, then run "
                     "`python3 llm/eval-v2/tally.py`.", ""], [
                     "# Rank best to worst, e.g.  w01_premise_scene: B > D > A > C", ""]
    for i, t in enumerate(tasks):
        cands = [c for c in short if any(w["id"] == t["id"] and w["seed"] == 101 for w in res[c]["writing"])]
        if len(cands) < 2:
            continue  # nothing to rank
        random.Random(9000 + i).shuffle(cands)
        key[t["id"]] = {LABELS[k]: c for k, c in enumerate(cands)}
        P += ["---", f"## {t['id']}", "", "**Task:** " + t["prompt"].replace("\n", " "), ""]
        for k, c in enumerate(cands):
            w = next(w for w in res[c]["writing"] if w["id"] == t["id"] and w["seed"] == 101)
            P += [f"### {LABELS[k]}", "", w["text"].strip() or "_(empty response)_", ""]
        B.append(f"{t['id']}: " + " > ".join("_" for _ in cands))
    open(os.path.join(a.report_dir, "review_packet.md"), "w").write("\n".join(P) + "\n")
    open(os.path.join(a.report_dir, "ballot.txt"), "w").write("\n".join(B) + "\n")
    os.makedirs(os.path.dirname(a.key_path), exist_ok=True)
    json.dump(key, open(a.key_path, "w"), indent=2)
    L += [f"Blind review packet: `review_packet.md` ({len(short)} writers x {len(tasks)} prompts).", ""]
    open(os.path.join(a.report_dir, "results.md"), "w").write("\n".join(L) + "\n")
    print("wrote", a.report_dir, "and key", a.key_path)


if __name__ == "__main__":
    main()
