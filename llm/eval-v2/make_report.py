#!/usr/bin/env python3
"""make_report.py — aggregate eval-v2 results + judgments into a report and a blind review packet.

Outputs:
  <report-dir>/results.md        coding + writing tables (judge scores exclude self-judgments)
  <report-dir>/review_packet.md  blind human review: top-N writers by judge score, labels A-D
  <report-dir>/ballot.txt        fill-in ranking template for the packet
  <key-path>                     label -> model key (kept out of the reports dir; not committed)
"""

import argparse
import collections
import glob
import json
import os
import random
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from judge import CRITERIA  # noqa: E402
from tasks_writing import all_writing_tasks  # noqa: E402

LABELS = "ABCDEFGHIJ"


def load(results_dir, judgments_dir):
    res = {}
    for f in sorted(glob.glob(os.path.join(results_dir, "*.json"))):
        r = json.load(open(f))
        res[r["candidate"]] = r
    judg = []
    for f in sorted(glob.glob(os.path.join(judgments_dir, "*.jsonl"))):
        judg += [json.loads(ln) for ln in open(f) if ln.strip()]
    return res, judg


# A judge must not score a model it is (a variant of): same weights at a different quantisation
# or runtime. Keys are judge names, values are candidate names treated as "self" for that judge.
SELF_ALIASES = {"qwen2.5-14b": {"qwen2.5-14b-ov-int4"}}


def is_self(j):
    return bool(j.get("self")) or j["candidate"] in SELF_ALIASES.get(j["judge"], set())


def judge_table(judg):
    """Per-judge standardised scores.

    Judges grade on different scales (here a 6.85 mean vs a 5.25 mean), so raw scores from
    different judges must not be pooled: a candidate that only the lenient judge could score
    (because it is the harsh judge itself) would look better than it is. Each sample score is
    converted to a z-score against that judge's own distribution over ALL its samples, then a
    candidate's z is the mean over its non-self samples. `raw` keeps the unstandardised
    per-judge means so nothing is hidden.
    """
    import math
    ov = lambda s: statistics.mean(s[k] for k in CRITERIA)  # noqa: E731
    stats = {}
    for judge in {j["judge"] for j in judg}:
        valid = [j["scores"] for j in judg if j["judge"] == judge and j.get("scores")]
        st = {"overall": (statistics.mean(ov(s) for s in valid), statistics.pstdev([ov(s) for s in valid]) or 1.0)}
        for k in CRITERIA:
            st[k] = (statistics.mean(s[k] for s in valid), statistics.pstdev([s[k] for s in valid]) or 1.0)
        stats[judge] = st
    z = collections.defaultdict(lambda: collections.defaultdict(list))
    raw = collections.defaultdict(lambda: collections.defaultdict(list))
    judges = collections.defaultdict(set)
    for j in judg:
        if is_self(j) or not j.get("scores"):
            continue
        s, c, jn = j["scores"], j["candidate"], j["judge"]
        z[c]["overall"].append((ov(s) - stats[jn]["overall"][0]) / stats[jn]["overall"][1])
        for k in CRITERIA:
            z[c][k].append((s[k] - stats[jn][k][0]) / stats[jn][k][1])
        raw[c][jn].append(ov(s))
        judges[c].add(jn)
    out = {}
    for c, d in z.items():
        row = {k: round(statistics.mean(v), 2) for k, v in d.items()}
        row["n"] = len(d["overall"])
        row["judges"] = sorted(judges[c])
        row["raw"] = {jn: round(statistics.mean(v), 2) for jn, v in raw[c].items()}
        out[c] = row
    return out, {jn: (round(m, 2), round(sd, 2)) for jn, st in stats.items() for m, sd in [st["overall"]]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", required=True)
    ap.add_argument("--judgments-dir", required=True)
    ap.add_argument("--report-dir", required=True)
    ap.add_argument("--key-path", required=True)
    ap.add_argument("--shortlist", type=int, default=4)
    a = ap.parse_args()
    res, judg = load(a.results_dir, a.judgments_dir)
    jt, jstats = judge_table(judg)
    os.makedirs(a.report_dir, exist_ok=True)
    L = ["# eval-v2 results", "",
         "Generated by `llm/eval-v2/make_report.py`. Method: `llm/eval-v2/README.md`. Raw outputs:",
         "`reports/data/eval-v2/`.", ""]

    # ---- coding ----
    L += ["## Coding (15 tasks, executed against hidden tests)", "",
          "| candidate | greedy pass@1 | sampled pass rate (3x, T=0.6) | bugfix | class | parsing | graph | algorithm | utility | median tok/s |",
          "|:--|:--:|:--:|:--:|:--:|:--:|:--:|:--:|:--:|--:|"]
    cats = ["bugfix", "class", "parsing", "graph", "algorithm", "utility"]
    order = sorted((c for c in res if res[c]["coding"]),
                   key=lambda c: (-res[c]["summary"]["coding_pass_greedy"],
                                  -(res[c]["summary"]["coding_sampled_pass_rate"] or 0)))
    for c in order:
        s, rows = res[c]["summary"], res[c]["coding"]
        per = []
        for cat in cats:
            rs = [r for r in rows if r["category"] == cat]
            per.append(f"{sum(r['pass_greedy'] for r in rs)}/{len(rs)}" if rs else "-")
        L.append(f"| {c} | **{s['coding_pass_greedy']}/{s['coding_tasks']}** | "
                 f"{s['coding_sampled_pass_rate']:.0%} | " + " | ".join(per) + f" | {s['median_tok_s']} |")
    ids = []
    for c in order:
        ids += [r["id"] for r in res[c]["coding"] if r["id"] not in ids]
    L += ["", "Per task (greedy ✓/✗, then sampled passes out of 3):", "",
          "| task | " + " | ".join(order) + " |", "|:--|" + ":--:|" * len(order)]
    for tid in ids:
        cells = []
        for c in order:
            r = next((x for x in res[c]["coding"] if x["id"] == tid), None)
            cells.append("-" if r is None else ("✓" if r["pass_greedy"] else "✗") + f" {r['sampled_passes']}/3")
        L.append(f"| {tid} | " + " | ".join(cells) + " |")

    # ---- writing ----
    L += ["", "## Creative writing (10 prompts x 2 samples, T=0.8)", "",
          "The two judges grade on different scales (see the judge means below), so scores are "
          "**standardised per judge** (z-score against that judge's own distribution; 0 = that "
          "judge's average, +1 = one standard deviation better) and then averaged. A judge's "
          "scores of its own outputs, or of a variant of itself (Qwen2.5-14B vs its OpenVINO "
          "int4), are excluded, so gpt-oss-20b is rated by Qwen-14B alone and the two Qwen-14B "
          "variants by gpt-oss alone. Those three rest on **one** judge, so compare them with "
          "caution. Judges are about as capable as the candidates and favour polish, so this is "
          "a shortlist filter. The blind human ranking (`human_results.md`, once you fill in the "
          "ballot) is the primary signal.", "",
          "| candidate | judge z (overall) | qwen-14B judge raw | gpt-oss judge raw | adherence z | craft z | originality z | voice z | coherence z | judged samples | length in range | stock phrases /1k words | truncated / empty |",
          "|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
    worder = sorted(res, key=lambda c: -(jt.get(c, {}).get("overall") if c in jt else -99))
    for c in worder:
        s, j = res[c]["summary"], jt.get(c, {})
        raw = j.get("raw", {})
        L.append(f"| {c} | **{j.get('overall', '-')}** | {raw.get('qwen2.5-14b', '-')} | {raw.get('gpt-oss-20b', '-')} | "
                 + " | ".join(str(j.get(k, "-")) for k in CRITERIA)
                 + f" | {j.get('n', 0)} | {s['writing_length_ok']}/{s['writing_samples']} | "
                 f"{s['stock_per_1k_words_mean']} | {s['writing_truncated']} / {s['writing_empty']} |")
    jud = sorted({j["judge"] for j in judg})
    L += ["", f"Judges: {', '.join(jud) or 'none'}; raw overall mean / stdev per judge: "
          + ", ".join(f"{k} {v[0]} / {v[1]}" for k, v in sorted(jstats.items()))
          + f". Unparseable judge replies: {sum(1 for j in judg if j.get('error') == 'unparseable')}.", ""]

    # ---- blind review packet ----
    ranked = [c for c in worder if c in jt] or list(res)
    # One writer per model family: an OpenVINO int4 conversion is the same model as its dense
    # twin, so a human reading both learns almost nothing. The dense model represents the family.
    FAMILY = {"qwen2.5-14b-ov-int4": "qwen2.5-14b", "qwen2.5-7b-ov-int4": "qwen2.5-7b"}
    short, seen = [], set()
    for c in ranked:
        fam = FAMILY.get(c, c)
        if fam in seen or fam not in res:
            continue
        seen.add(fam)
        short.append(fam)
        if len(short) == a.shortlist:
            break
    L += [f"Human-review shortlist ({len(short)} writers): {', '.join(short)}. Rule: highest judge z, "
          "one writer per model family (Qwen2.5-14B stands in for its OpenVINO int4 twin). The top "
          "six candidates are within judge noise of each other, so which four make the cut is "
          "close to arbitrary; the packet exists to settle exactly that.", ""]
    tasks = all_writing_tasks()
    key, P, B = {}, ["# Blind writing review", "",
                     f"{len(short)} anonymous writers (top judge scores, one per model family), one sample each "
                     "(seed 101). Labels are shuffled per prompt, so 'A' is not the same writer twice. "
                     "Rank each prompt best to worst in `ballot.txt`, then run "
                     "`python3 llm/eval-v2/tally.py`.", ""], [
                     "# Rank best to worst, e.g.  w01_premise_scene: B > D > A > C", ""]
    for i, t in enumerate(tasks):
        cands = [c for c in short if any(w["id"] == t["id"] and w["seed"] == 101 for w in res[c]["writing"])]
        if len(cands) < 2:
            continue  # nothing to rank
        random.Random(9000 + i).shuffle(cands)
        key[t["id"]] = {LABELS[k]: c for k, c in enumerate(cands)}
        P += ["---", f"## {t['id']}", "", "**Task:** " + t["prompt"].replace("\n", " "), ""]
        for k, c in enumerate(cands):
            w = next(w for w in res[c]["writing"] if w["id"] == t["id"] and w["seed"] == 101)
            P += [f"### {LABELS[k]}", "", w["text"].strip() or "_(empty response)_", ""]
        B.append(f"{t['id']}: " + " > ".join("_" for _ in cands))
    # reading-time guide: prompts by total words across the shortlisted writers
    sizes = {}
    for t in tasks:
        sizes[t["id"]] = sum(len(w["text"].split()) for c in key.get(t["id"], {}).values()
                             for w in res[c]["writing"] if w["id"] == t["id"] and w["seed"] == 101)
    total = sum(sizes.values())
    quick, acc = [], 0
    for tid, n in sorted(sizes.items(), key=lambda kv: kv[1]):
        if n and acc + n <= total * 0.42:
            quick.append(tid); acc += n
    P[4:4] = [f"**Reading time:** all prompts is about {round(total / 230)} minutes (~{total} words). "
              f"**Short on time?** Rank only {', '.join(sorted(quick))} (~{round(acc / 230)} minutes). "
              "Prompts left as `_` in the ballot are simply skipped by the tally.", ""]
    open(os.path.join(a.report_dir, "review_packet.md"), "w").write("\n".join(P) + "\n")
    open(os.path.join(a.report_dir, "ballot.txt"), "w").write("\n".join(B) + "\n")
    os.makedirs(os.path.dirname(a.key_path), exist_ok=True)
    json.dump(key, open(a.key_path, "w"), indent=2)
    L += [f"Blind review packet: `review_packet.md` ({len(short)} writers x {len(tasks)} prompts).", ""]
    open(os.path.join(a.report_dir, "results.md"), "w").write("\n".join(L) + "\n")
    print("wrote", a.report_dir, "and key", a.key_path)


if __name__ == "__main__":
    main()
